// genmanifest writes internal/hostsec/manifest_gen.go: the SHA-256 of every
// file a release installs under /opt/hostpanel/{scripts,templates} plus the
// sudoers file and the systemd unit. The binary then knows what its own
// release looks like (Sunucu → script bütünlüğü). Run from the repo root:
//
//	go run ./tools/genmanifest
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"

	"github.com/zahit5834/hostpanel/internal/hostsec"
)

func main() {
	m, err := hostsec.BuildManifest("deploy")
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile("internal/hostsec/manifest_gen.go", renderManifest(m), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("manifest: %d dosya\n", len(m))
}

// renderManifest is the Go source of manifest_gen.go.
func renderManifest(m hostsec.Manifest) []byte {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/genmanifest; DO NOT EDIT.\n\npackage hostsec\n\n")
	b.WriteString("// releaseManifest is the SHA-256 of every installed file of this release.\n")
	b.WriteString("var releaseManifest = Manifest{\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%q: %q,\n", k, m[k])
	}
	b.WriteString("}\n")
	if src, err := format.Source(b.Bytes()); err == nil {
		return src
	}
	return b.Bytes()
}
